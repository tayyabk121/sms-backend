/** Enum representing the attendance status of a student. This enum is used to
 * indicate whether a student is present, absent, has a half-day attendance, or
 * if it's a holiday. It can be used in attendance tracking systems to manage
 * and record student attendance effectively.
 */
public enum StudentAttendanceStatus {
    PRESENT,
    ABSENT,
    HALF_DAY,
    HOLIDAY
}
