package com.example.sms.util;

/** Enum representing the attendance status of staff members in the application.
 * This enum is used to categorize the attendance status of staff members, such
 * as whether they are present, absent, on a half-day, on holiday, or if it's a
 * weekend.
 */
public enum StaffAttendanceStatus {
    PRESENT,
    ABSENT,
    HALF_DAY,
    HOLIDAY,
    WEEKEND
}
