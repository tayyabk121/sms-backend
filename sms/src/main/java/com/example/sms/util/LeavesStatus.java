package com.example.sms.util;

/** * Enum representing the status of leave applications in the system. This enum is
 * used to track the different stages of a leave application, such as pending,
 * approved, rejected, and cancelled. Each status helps in managing and
 * processing leave requests effectively within the application.
 */
public enum LeavesStatus {
    PENDING,
    APPROVED,
    REJECTED,
    CANCELLED
}
