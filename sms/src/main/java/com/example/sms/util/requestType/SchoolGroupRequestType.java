package com.example.sms.util.requestType;

/** Enum representing the types of branch-related requests in the application.
 * This enum is used to differentiate between various operations related to
 * branches, such as creating a new branch, finding a branch by its ID,
 * retrieving all branches, updating a branch's information,
 * and deleting a branch. */
public enum SchoolGroupRequestType {
    CREATE,
    FIND_BY_ID,
    FIND_ALL,
    UPDATE,
    DELETE,
}
