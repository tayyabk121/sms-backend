package com.example.sms.util;

/** Enum representing the status of staff members in the application. This enum is
 * used to indicate whether a staff member is active, inactive, on leave, or has
 * resigned. It helps in managing staff information and their availability for
 * work-related tasks.
 */
public enum StaffStatus {
    ACTIVE,
    INACTIVE,
    ON_LEAVE,
    RESIGNED
}
