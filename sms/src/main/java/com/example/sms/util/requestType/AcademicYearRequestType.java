package com.example.sms.util.requestType;

/** * Enum representing the types of requests related to academic years
 * in the application. This enum is used to differentiate between various
 * operations that can be performed on academic year entities, such as
 * creating, updating, deleting, and retrieving
 * academic year information.
 */
public enum AcademicYearRequestType {
    CREATE,
    UPDATE,
    DELETE,
    FIND_BY_ID,
    FIND_ALL
}
