package com.example.sms.util;

/** Enum representing the gender of a user. This enum is used to specify the
 * gender of a user in the application, allowing for better categorization
 * and personalization of user experiences. The enum includes three constants:
 * - MALE: Represents a male user.
 * - FEMALE: Represents a female user.
 * - OTHER: Represents a user who identifies as a gender other than male or
 * female. based on their specified gender. */
public enum Gender {
    MALE,
    FEMALE,
    OTHER
}
