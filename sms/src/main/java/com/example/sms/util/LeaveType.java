package com.example.sms.util;

/** Enum representing different types of leave that an employee can take.
 * This enum is used to categorize and manage various leave types within the
 * application, such as casual leave, sick leave, maternity leave, paternity
 * leave, and unpaid leave.
 */
public enum LeaveType {
    CASUAL,
    SICK,
    MATERNITY,
    PATERNITY,
    UNPAID
}
